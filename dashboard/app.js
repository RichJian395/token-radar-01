  function modelPanel() {
    var m = DATA.model;
    var sandboxNote;
    if (sandbox.on) {
      var moved = 0;
      var re = displayRows();
      re.forEach(function (r) {
        var orig = DATA.rows.filter(function (o) { return o.slug === r.slug; })[0];
        if (orig && orig.rank !== r.rank) moved++;
      });
      sandboxNote = el('p', { class: 'sandbox-note', html: 'Sandbox on: these constants re-rank the board live — <b>' + moved + ' of ' + DATA.board_size + ' rows moved</b>. The submitted board.json keeps the published constants above.' });
    } else {
      sandboxNote = el('p', { class: 'sandbox-note', text: 'Move a slider to re-rank the board with your own constants. The submitted board.json keeps the published ones.' });
    }
    function slider(id, label, min, max, step, value, fmt) {
      var out = el('output', { for: id, text: fmt(value) });
      var input = el('input', { type: 'range', id: id, min: String(min), max: String(max), step: String(step), value: String(value), 'aria-label': label });
      input.addEventListener('input', function () {
        var v = parseFloat(input.value);
        if (id === 'sb-growth') sandbox.growth = v;
        else if (id === 'sb-floor') sandbox.floor = v;
        else sandbox.chain = v;
        sandbox.on = sandbox.growth !== m.growth_weight || sandbox.floor !== m.maturity_floor || sandbox.chain !== m.chain_bonus;
        out.textContent = fmt(v);
        render();
      });
      return el('div', { class: 'field' }, el('label', { for: id, text: label }), input, out);
    }
    var reset = el('button', { class: 'button', type: 'button', text: 'Reset to published constants', onclick: function () {
      sandbox.growth = m.growth_weight; sandbox.floor = m.maturity_floor; sandbox.chain = m.chain_bonus; sandbox.on = false; render();
    } });
    return el('section', { class: 'panel model' },
      el('h2', { text: 'How implied value is computed' }),
      el('p', { class: 'sub', text: 'Every row is scored by one function of the snapshot figures. No protocol name is special-cased, and no row is hand-picked.' }),
      el('div', { class: 'formula' },
        'implied = round( tvl_usd x category_multiple x (1 + clamp(change_7d, ' + m.growth_floor + ', ' + m.growth_cap + ') / 100 x ' + m.growth_weight + ') x (' + m.maturity_floor + ' + min(age_days, ' + m.maturity_days + ') / ' + m.maturity_days + ' x ' + (1 - m.maturity_floor).toFixed(1) + ') x (1 + ' + m.chain_bonus + ' x min(chains, ' + m.chain_cap + ')) )'
      ),
      el('table', null, el('tbody', null,
        el('tr', null, el('td', { text: 'fee engine x ' + m.multiple_fee_engine }), el('td', { text: 'Dexs, lending, derivatives, yield, CDP, allocators: usage earns fees a token can capture.' })),
        el('tr', null, el('td', { text: 'neutral x ' + m.multiple_neutral }), el('td', { text: 'Everything else: the token would capture part of the value the protocol holds.' })),
        el('tr', null, el('td', { text: 'pass-through x ' + m.multiple_pass_through }), el('td', { text: 'Bridges, chains, liquid staking: value passes through that belongs to another asset.' }))
      )),
      el('p', { class: 'sub', text: 'TVL and seven-day growth come from the snapshot; growth is clamped so one wild week cannot crown a protocol. Age is the time since the protocol was first listed, the best record of how long it has run with no token on record; an unlisted age uses ' + m.unknown_age_days + ' days. Chain breadth adds 2% a chain, up to five, for distribution.' }),
      el('h3', { text: 'Model sandbox' }),
      el('div', { class: 'sandbox' },
        slider('sb-growth', 'Growth weight', 0, 1, 0.05, sandbox.growth, function (v) { return v.toFixed(2); }),
        slider('sb-floor', 'Maturity floor', 0.4, 0.8, 0.05, sandbox.floor, function (v) { return v.toFixed(2); }),
        slider('sb-chain', 'Chain bonus', 0, 0.05, 0.005, sandbox.chain, function (v) { return v.toFixed(3); })
      ),
      el('div', null, sandboxNote, reset)
    );
  }

  var dialog = el('dialog', { class: 'detail', id: 'detail', 'aria-labelledby': 'detail-title' });
  dialog.addEventListener('close', function () { state.selected = null; writeHash(); });

  function peersOf(row) {
    return DATA.rows
      .filter(function (r) { return r.slug !== row.slug && r.category === row.category; })
      .map(function (r) { return { r: r, d: Math.abs(Math.log((r.tvl_usd || 1) / (row.tvl_usd || 1))) }; })
      .sort(function (a, b) { return a.d - b.d; })
      .slice(0, 3)
      .map(function (x) { return x.r; });
  }

  function openDetail(slug) {
    var row = DATA.rows.filter(function (r) { return r.slug === slug; })[0];
    if (!row) return;
    state.selected = slug;
    writeHash();
    dialog.textContent = '';
    var steps = farmSteps(row);
    var peers = peersOf(row);
    var recomputed = impliedOf(row, DATA.model);
    dialog.appendChild(el('div', { class: 'detail-head' },
      el('div', null,
        el('span', { class: 'brand-name', text: 'Rank ' + row.rank + ' of ' + DATA.board_size + (WATCH[row.slug] ? ' — watchlist' : '') }),
        el('h2', { id: 'detail-title', text: row.name }),
        el('p', { class: 'sub', text: (row.category || 'Other') + ' on ' + (row.chains && row.chains.length ? row.chains.join(', ') : 'an unnamed chain') })
      ),
      el('button', { class: 'close', type: 'button', 'aria-label': 'Close details', text: 'Close', onclick: function () { dialog.close(); } })
    ));
    dialog.appendChild(el('section', { class: 'detail-section' },
      el('h3', { text: 'Implied value' }),
      el('div', { class: 'equation' },
        el('div', null, el('span', { text: 'TVL' }), el('b', { class: 'num', text: fmtUsd(row.tvl_usd) })),
        el('div', null, el('span', { text: 'Category tier (' + row.category_tier + ')' }), el('b', { class: 'num', text: 'x ' + row.category_multiple })),
        el('div', null, el('span', { text: 'Seven-day growth' }), el('b', { class: 'num', text: fmtPct(row.change_7d) })),
        el('div', null, el('span', { text: 'Growth multiplier' }), el('b', { class: 'num', text: String(row.growth_multiplier) })),
        el('div', null, el('span', { text: 'Age with no token' }), el('b', { class: 'num', text: fmtAge(row.age_days) })),
        el('div', null, el('span', { text: 'Maturity multiplier' }), el('b', { class: 'num', text: String(row.maturity_multiplier) })),
        el('div', null, el('span', { text: 'Chains (' + (row.chains || []).length + ')' }), el('b', { class: 'num', text: 'x ' + row.chain_multiplier })),
        el('div', null, el('span', { text: 'Implied value' }), el('b', { class: 'num', text: fmtUsd(row.implied_value_usd) }))
      ),
      el('p', { class: 'sub', text: 'Model ' + DATA.model_version + ': the same function scores every protocol. The page recomputes this row as ' + fmtUsd(recomputed) + (recomputed === row.implied_value_usd ? ', the same number board.json carries.' : ', which differs from the board: the data would be stale.') + ' This is an estimate, not a price.' })
    ));
    dialog.appendChild(el('section', { class: 'detail-section' },
      el('h3', { text: 'Farm plan' }),
      el('ol', { class: 'steps' }, steps.map(function (s) {
        var at = s.indexOf(' Cost: ');
        var action = at >= 0 ? s.slice(0, at) : s;
        var tail = at >= 0 ? s.slice(at + 1) : '';
        return el('li', null, el('b', { text: action }), el('span', { class: 'cost', text: tail }));
      }))
    ));
    if (peers.length > 0) {
      dialog.appendChild(el('section', { class: 'detail-section' },
        el('h3', { text: 'Nearest peers in ' + (row.category || 'its category') }),
        el('div', { class: 'peers' }, peers.map(function (p) {
          return el('div', { class: 'peer' },
            el('span', { text: '#' + p.rank + ' ' + p.name + ' — TVL ' + fmtUsd(p.tvl_usd) }),
            el('b', { text: fmtUsd(p.implied_value_usd) })
          );
        }))
      ));
    }
    dialog.appendChild(el('p', { class: 'note', text: 'This protocol records no token in the snapshot. That is what its DefiLlama record shows, not proof it has none — and nothing here predicts whether or when it launches one.' }));
    if (typeof dialog.showModal === 'function') {
      if (!dialog.open) dialog.showModal();
    } else {
      dialog.setAttribute('open', '');
    }
  }

  function render() {
    app.textContent = '';
    var shell = el('div', { class: 'shell' });
    shell.appendChild(header());
    shell.appendChild(lede());
    shell.appendChild(controls());
    shell.appendChild(state.tab === 'pre-token' ? boardTable() : state.tab === 'live' ? liveTable() : setAsideTable());
    if (state.tab === 'pre-token') shell.appendChild(modelPanel());
    app.appendChild(shell);
    app.setAttribute('aria-busy', 'false');
    if (!dialog.isConnected) app.appendChild(dialog);
    if (state.selected) openDetail(state.selected);
  }

  readHash();
  render();
  window.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && dialog.open) dialog.close();
  });
